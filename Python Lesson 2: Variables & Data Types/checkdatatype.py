# Check Data Type Using type()
age = 20
print(type(age))

name = "Prince"
print(type(name))

# Python is Dynamically Typed

# You can change type anytime:

x = 10
x = "Hello"
print(x)

# No error. Python is flexible 

# Variable Naming Rules
# ✅ Allowed:

my_name = "Prince"
age2 = 21
_total = 100

# Not allowed:

# 2age = 20      # starts with number
# my-name = 10   # hyphen not allowed
# class = 5      # reserved keyword
